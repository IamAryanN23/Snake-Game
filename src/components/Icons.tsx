export function ChevronIcon({
  direction,
  ...props
}: IconProps & { direction: 'up' | 'down' | 'left' | 'right' }) {
  const rotation =
    direction === 'up'
      ? 'rotate(0)'
      : direction === 'right'
        ? 'rotate(90)'
        : direction === 'down'
          ? 'rotate(180)'
          : 'rotate(270)'

  return (
    <svg
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth="2.4"
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      {...props}
    >
      <g transform={`${rotation} 12 12`}>
        <path d="m6 14 6-6 6 6" />
      </g>
    </svg>
  )
}

